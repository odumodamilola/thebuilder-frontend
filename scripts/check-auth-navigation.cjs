const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const compiled = ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/lib/return-path.ts'), 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText;
const exportsObject = {};
vm.runInNewContext(compiled, {exports: exportsObject, URL});
const {safeReturnPath, withReturnPath, signInDestination} = exportsObject;
const destination = '/console/content?q=Older%20story&edition=Australia&page=2';
for (const value of ['/', '/account', destination, '/stories/example#discussion']) assert.equal(safeReturnPath(value), value);
for (const value of [undefined, ['//evil.example'], 42, '', 'https://evil.example', '//evil.example', '/\\evil.example', '/%5cevil.example', '/%2fevil.example', '/%09/evil.example', '/path\nheader', '/path?value=%0d%0a', '/bad%ZZ', ' /console']) assert.equal(safeReturnPath(value), undefined, String(value));
const reader = {email: 'reader@example.test', emailVerified: true, mfaRequired: false, mfaEnabled: false, onboardingComplete: true};
assert.equal(signInDestination(reader, destination), destination);
assert.equal(signInDestination(reader, '//evil.example'), '/account');
assert.equal(signInDestination({...reader, onboardingComplete: false}, undefined), '/onboarding');
const privileged = {...reader, mfaRequired: true, mfaEnabled: true};
const challenge = new URL(signInDestination(privileged, destination), 'https://return.invalid');
assert.equal(challenge.pathname, '/mfa');
assert.equal(challenge.searchParams.get('redirect'), destination);
assert.equal(safeReturnPath(challenge.searchParams.get('redirect')), destination);
assert.equal(new URL(signInDestination({...privileged, mfaEnabled: false}, destination), 'https://return.invalid').pathname, '/mfa-setup');
const verify = new URL(signInDestination({...privileged, emailVerified: false}, destination), 'https://return.invalid');
assert.equal(verify.pathname, '/verify-email');
assert.equal(verify.searchParams.get('email'), reader.email);
assert.equal(verify.searchParams.get('redirect'), destination);
assert.equal(withReturnPath('/mfa', '/\\evil.example'), '/mfa');
console.log('Authentication navigation: same-origin return validation, login, email verification and MFA continuation pass.');
