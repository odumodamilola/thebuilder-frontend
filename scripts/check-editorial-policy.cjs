const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {createLoader} = require('./ts-module.cjs');
const load = createLoader();
const policy = require('../contracts/editorial-policy.json');
const backendPolicy = path.resolve(__dirname, '../../.replatform/laravel12-backend/config/editorial-policy.json');
if (fs.existsSync(backendPolicy)) assert.deepEqual(JSON.parse(fs.readFileSync(backendPolicy, 'utf8')), policy);
assert.deepEqual(policy.categories.Australia, ['Business','Startups','Community','Entrepreneurs','Academia','Research','Policy','Interviews']);
assert.deepEqual(policy.categories.Nigeria, ['Business','Startups','Community','Entrepreneurs','Academia','Diaspora','Interviews']);
assert.deepEqual(policy.regions, ['Australia','Africa','UK','US','Canada']);
const {normalizeSiteSettings, footerForEdition, defaultSiteMenus} = load(path.join(__dirname, '../src/lib/site-settings.ts'));
const defaults = normalizeSiteSettings({footer:'© The Builder. Powered by Osun Tech Exchange'});
assert.equal(footerForEdition(defaults, 'Australia'), '© The Builder. Powered by TechPro Consulting Pty Ltd');
assert.equal(footerForEdition(defaults, 'Nigeria'), '© The Builder. Powered by TechPro Nigeria');
const custom = normalizeSiteSettings({footer:'Shared footer', footerAustralia:'Australia edition attribution'});
assert.equal(footerForEdition(custom, 'Australia'), 'Australia edition attribution');
assert.equal(footerForEdition(custom, 'Nigeria'), 'Shared footer');
assert.deepEqual(Array.from(defaultSiteMenus, item => item.url), ['/','/stories','/builders','/videos','/opportunities']);
console.log('Editorial policy: exact edition categories, focus regions, compact navigation, edition attribution and frontend/API policy parity pass.');
